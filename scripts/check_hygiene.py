"""Fail on hidden Unicode controls or undisclosed co-authoring footers."""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FORBIDDEN = {
    0xFEFF, 0x200B, 0x200C, 0x200D, 0x2060, 0x00AD,
    0x200E, 0x200F, 0x202A, 0x202B, 0x202C, 0x202D, 0x202E,
    0x2066, 0x2067, 0x2068, 0x2069,
}
BAD_FOOTERS = ("Co-authored-by:" + " ChatGPT", "Co-authored-by:" + " OpenAI", "Generated by" + " ChatGPT")
errors = []
for folder in ["docs", "src", "tests", "scripts", ".github"]:
    for path in (ROOT / folder).rglob("*"):
        if not path.is_file() or "__pycache__" in path.parts:
            continue
        if path.suffix not in (".md", ".py", ".yml", ".yaml", ".txt", ".json"):
            continue
        content = path.read_text(encoding="utf-8")
        for i, ch in enumerate(content):
            if ord(ch) in FORBIDDEN:
                errors.append("%s: hidden U+%04X at character %d" % (path.relative_to(ROOT), ord(ch), i))
        for footer in BAD_FOOTERS:
            if footer in content:
                errors.append("%s: disallowed attribution footer" % path.relative_to(ROOT))
if errors:
    raise SystemExit("\n".join(errors))
print("Text hygiene: PASS (no forbidden hidden code points or disallowed footers)")
